'use client';

import React, { useState } from 'react';
import { FolderOpen, Upload, Image as ImageIcon, FileText, Film, Plus } from 'lucide-react';
import { SignatureHeroCard } from '@/components/hero/SignatureHeroCard';
import { useWorkspaceStore } from '@/stores/workspaceStore';

export default function MediaLibraryPage() {
  const { getCurrentBusiness } = useWorkspaceStore();
  const business = getCurrentBusiness();

  const [mediaAssets, setMediaAssets] = useState<
    Array<{
      id: string;
      name: string;
      type: string;
      size: string;
      dimensions: string;
      uploadedAt: string;
    }>
  >([]);

  return (
    <div className="animate-page-enter space-y-5">
      <SignatureHeroCard
        tagBadge={`${business?.name || 'CrossTech'} • Media Assets`}
        title="Branded Media Library & Slide Assets"
        description="Business-scoped media storage. Visual assets, typography templates, and carousel slide images generated by AI or uploaded by design teams."
        primaryAction={
          <label className="btn-hero-primary cursor-pointer">
            <Upload className="w-3.5 h-3.5" />
            <span>Upload Assets</span>
            <input
              type="file"
              multiple
              accept="image/*,video/*"
              className="hidden"
              onChange={(e) => {
                const files = e.target.files;
                if (!files || files.length === 0) return;
                const newItems = Array.from(files).map((f, i) => ({
                  id: `media-${Date.now()}-${i}`,
                  name: f.name,
                  type: f.type,
                  size: `${(f.size / (1024 * 1024)).toFixed(1)} MB`,
                  dimensions: 'Original',
                  uploadedAt: 'Just now',
                }));
                setMediaAssets((prev) => [...newItems, ...prev]);
              }}
            />
          </label>
        }
      />

      {mediaAssets.length === 0 ? (
        <div className="card p-12 text-center max-w-xl mx-auto space-y-3">
          <div className="w-12 h-12 rounded-2xl bg-slate-100 border border-slate-200 flex items-center justify-center mx-auto text-slate-400">
            <FolderOpen className="w-6 h-6" />
          </div>
          <h3 className="font-heading font-bold text-lg text-neutral-900">
            Your media library is empty
          </h3>
          <p className="text-xs text-slate-500 max-w-md mx-auto">
            Upload your brand logos, custom graphics, or generate typography slides directly with the Visual Designer persona.
          </p>
          <label className="btn btn-primary mt-2 cursor-pointer">
            <Upload className="w-3.5 h-3.5" />
            <span>Upload Files</span>
            <input
              type="file"
              multiple
              accept="image/*,video/*"
              className="hidden"
              onChange={(e) => {
                const files = e.target.files;
                if (!files || files.length === 0) return;
                const newItems = Array.from(files).map((f, i) => ({
                  id: `media-${Date.now()}-${i}`,
                  name: f.name,
                  type: f.type,
                  size: `${(f.size / (1024 * 1024)).toFixed(1)} MB`,
                  dimensions: 'Original',
                  uploadedAt: 'Just now',
                }));
                setMediaAssets((prev) => [...newItems, ...prev]);
              }}
            />
          </label>
        </div>
      ) : (
        <div className="grid grid-cols-4 gap-4">
          {mediaAssets.map((asset) => (
            <div key={asset.id} className="card p-4 space-y-3 hover:border-slate-400 transition-all">
              <div className="w-full h-32 rounded-md bg-slate-100 border border-slate-200 flex items-center justify-center text-slate-400">
                {asset.type.startsWith('video') ? (
                  <Film className="w-8 h-8" />
                ) : (
                  <ImageIcon className="w-8 h-8" />
                )}
              </div>

              <div>
                <div className="text-xs font-semibold text-neutral-900 truncate" title={asset.name}>
                  {asset.name}
                </div>
                <div className="flex items-center justify-between text-[11px] text-slate-500 font-mono mt-1">
                  <span>{asset.dimensions}</span>
                  <span>{asset.size}</span>
                </div>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
